from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import shutil
import subprocess
import tempfile

from PySide6.QtCore import QByteArray, QRectF, Qt
from PySide6.QtGui import QPainter
from PySide6.QtSvg import QSvgRenderer


@dataclass
class LatexSvg:
    renderer: QSvgRenderer
    width: float
    height: float

    @property
    def aspect(self) -> float:
        return self.width / self.height

    def draw(self, painter: QPainter, bounds: QRectF, alignment=Qt.AlignmentFlag.AlignLeft) -> None:
        width = min(bounds.width(), bounds.height() * self.aspect)
        if alignment & Qt.AlignmentFlag.AlignRight:
            x = bounds.right() - width
        elif alignment & Qt.AlignmentFlag.AlignHCenter:
            x = bounds.center().x() - width / 2
        else:
            x = bounds.left()
        height = width / self.aspect
        y = bounds.center().y() - height / 2
        self.renderer.render(painter, QRectF(x, y, width, height))

    def draw_natural(self, painter: QPainter, x: float, center_y: float, scale: float) -> float:
        width, height = self.width * scale, self.height * scale
        self.renderer.render(painter, QRectF(x, center_y - height / 2, width, height))
        return width


_CACHE: dict[tuple[tuple[str, str], ...], dict[str, LatexSvg] | None] = {}


def latex_labels(specifications: dict[str, tuple[str, str]]) -> dict[str, LatexSvg] | None:
    """Compile a small label set to cropped SVG pages, once per process."""
    key = tuple(specifications.items())
    if key in _CACHE:
        return _CACHE[key]
    latex = shutil.which("latex")
    dvisvgm = shutil.which("dvisvgm")
    if latex is None or dvisvgm is None:
        _CACHE[key] = None
        return None
    pages = []
    for expression, color in specifications.values():
        pages.append(f"{{\\color[HTML]{{{color}}}{expression}}}\\newpage")
    source = "\n".join((
        r"\documentclass[12pt]{article}",
        r"\usepackage[utf8]{inputenc}",
        r"\usepackage[T1]{fontenc}",
        r"\usepackage{xcolor}",
        r"\pagestyle{empty}",
        r"\setlength{\parindent}{0pt}",
        r"\begin{document}",
        *pages,
        r"\end{document}",
    ))
    try:
        with tempfile.TemporaryDirectory(prefix="aci-latex-") as directory:
            root = Path(directory)
            tex = root / "labels.tex"
            tex.write_text(source, encoding="utf-8")
            subprocess.run(
                [latex, "-interaction=nonstopmode", "-halt-on-error", tex.name],
                cwd=root, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            subprocess.run(
                [dvisvgm, "--bbox=min", "--page=1-", "--output=label-%p.svg", "labels.dvi"],
                cwd=root, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            result: dict[str, LatexSvg] = {}
            pages = sorted(root.glob("label-*.svg"))
            if len(pages) != len(specifications):
                raise RuntimeError("LaTeX label page count mismatch")
            for page, name in zip(pages, specifications, strict=True):
                data = page.read_bytes()
                renderer = QSvgRenderer(QByteArray(data))
                size = renderer.defaultSize()
                if not renderer.isValid() or size.height() <= 0:
                    raise RuntimeError("invalid SVG generated by LaTeX")
                result[name] = LatexSvg(renderer, float(size.width()), float(size.height()))
    except (OSError, RuntimeError, subprocess.SubprocessError):
        result = None
    _CACHE[key] = result
    return result
